import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createPreviewServer } from './preview.mjs';
import { validateTour } from '../public/tours.js';

// Exercise the real editor, source, and playback through normal UI controls.
const temporary = await mkdtemp(path.join(os.tmpdir(), 'space-drift-tour-'));
const output = new URL('../artifacts/tour-editor/', import.meta.url);
let server, browser;
try {
  const folder = path.join(temporary, 'workspace');
  await mkdir(path.join(folder, 'src'), { recursive: true });
  await writeFile(path.join(folder, 'README.md'), '# Tour fixture\nRead this file before exploring the source.\n');
  await writeFile(path.join(folder, 'src', 'main.js'), 'export const answer = 42;\n');
  await mkdir(output, { recursive: true });
  server = await createPreviewServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ ...(process.env.CHANNEL ? { channel: process.env.CHANNEL } : {}), headless: true, args: ['--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.setDefaultTimeout(20000);
  const errors = [], requests = [];
  page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
  page.on('request', request => requests.push({ url: request.url(), method: request.method() }));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(() => !document.querySelector('#snapshot-picker').disabled);
  const connect = async () => {
    const chooser = page.waitForEvent('filechooser');
    await page.locator('#snapshot-picker').click();
    await (await chooser).setFiles(folder);
  };
  await connect();
  await page.locator('#launch').click();
  console.log('Connected a snapshot through the folder picker.');
  await page.locator('#tour-button').click();
  await page.locator('#tour-edit').click();
  await page.locator('#editor-preview').click();
  assert.match(await page.locator('#editor-status').innerText(), /between 1 and 64/);
  await page.locator('#editor-id').fill('workspace-guide');
  await page.locator('#editor-title').fill('Workspace guide');
  await page.locator('#editor-description').fill('Read the overview and source.');
  await page.locator('#editor-atlas').click();
  await page.locator('#atlas-search').fill('README');
  await page.locator('.atlas-row').filter({ hasText: 'README.md' }).getByRole('button', { name: 'Add to tour', exact: true }).click();
  await page.getByLabel('Stop 1 title', { exact: true }).fill('Overview');
  await page.getByLabel('Stop 1 explanation', { exact: true }).fill('<b>Read this first.</b>');
  await page.locator('#editor-atlas').click();
  await page.locator('.atlas-row').filter({ has: page.locator('strong', { hasText: /^src$/ }) }).getByRole('button', { name: 'Add to tour', exact: true }).click();
  assert.equal(await page.locator('.editor-stop').count(), 2);
  await page.locator('.editor-stop').nth(1).getByRole('button', { name: 'Move up' }).click();
  assert.equal(await page.getByLabel('Stop 2 title', { exact: true }).inputValue(), 'Overview');
  await page.locator('.editor-stop').nth(0).getByRole('button', { name: 'Move down' }).click();
  await page.locator('.editor-stop').nth(1).getByRole('button', { name: 'Remove stop' }).click();
  assert.equal(await page.locator('.editor-stop').count(), 1);
  await page.locator('#editor-validate').click();
  await page.waitForFunction(() => document.querySelector('#editor-status').textContent === 'All 1 stops are available.');
  await page.screenshot({ path: new URL('desktop.png', output).pathname });

  const downloadPromise = page.waitForEvent('download');
  await page.locator('#editor-export').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'workspace-guide.json');
  const exported = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(validateTour(exported).error, null);
  assert.equal(exported.description, 'Read the overview and source.');
  assert.equal(exported.stops[0].title, 'Overview');
  assert.equal(exported.stops[0].note, '<b>Read this first.</b>');
  assert.equal('missing' in exported.stops[0], false);
  console.log('Authored and exported a valid tour through Atlas and the editor.');

  await page.locator('#editor-preview').click();
  await page.waitForFunction(() => document.querySelector('#file-viewer').open, null, { timeout: 60000 });
  await page.waitForFunction(() => document.querySelector('#viewer-content').getAttribute('aria-busy') === 'false');
  assert.match(await page.locator('#viewer-content').innerText(), /Tour fixture/);
  assert.equal(await page.locator('#tour-note-title').innerText(), 'Overview');
  assert.equal(await page.locator('#tour-note-text').textContent(), '<b>Read this first.</b>');
  assert.equal(await page.locator('#tour-note-text b').count(), 0);
  await page.getByRole('button', { name: 'Close file and return to flight', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#tour-status').textContent.includes('Tour complete'));
  await page.locator('#tour-edit').click();
  assert.equal(await page.getByLabel('Stop 1 title', { exact: true }).inputValue(), 'Overview');
  await page.locator('#editor-selected').click();
  assert.equal(await page.locator('.editor-stop').count(), 2, 'The last selected file can be added directly.');

  await page.locator('.editor-import summary').click();
  const importJSON = async value => page.locator('#editor-import').setInputFiles({ name: 'route.json', mimeType: 'application/json', buffer: Buffer.from(value) });
  await importJSON('{');
  await page.waitForFunction(() => document.querySelector('#editor-status').textContent.includes('Invalid tour JSON'));
  assert.equal(await page.locator('.editor-stop').count(), 2, 'Invalid imports retain the draft.');
  const relative = { ...exported, stops: [{ path: 'README.md', title: 'Imported title' }, { path: 'missing.md' }] };
  await page.locator('#editor-import-body').selectOption(exported.stops[0].planet);
  await importJSON(JSON.stringify(relative));
  await page.waitForFunction(() => document.querySelector('#editor-status').textContent.includes('1 of 2 stops are unavailable'));
  assert.match(await page.locator('.editor-stop').nth(1).innerText(), /file is not mapped/);
  assert.equal(await page.getByLabel('Stop 1 title', { exact: true }).inputValue(), 'Imported title');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: new URL('mobile.png', output).pathname });
  assert.ok(await page.locator('#tour-editor').evaluate(node => node.scrollWidth <= node.clientWidth), 'The editor fits a narrow viewport.');
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole('button', { name: 'Close tour editor', exact: true }).click();
  await page.locator('#disconnect-folder').click();
  await connect();
  await page.locator('#launch').click();
  await page.locator('#tour-button').click();
  await page.locator('#tour-edit').click();
  assert.equal(await page.locator('.editor-stop').count(), 0, 'Disconnect clears the in-memory draft.');
  assert.equal(await page.locator('#editor-title').inputValue(), 'My tour');
  assert.deepEqual(errors, []);
  assert.equal(requests.some(request => request.method !== 'GET' || new URL(request.url).pathname.startsWith('/api/')), false, 'Authoring never writes or uses the scanning API for browser folders.');
  console.log('Verified Atlas files/folders, selection, annotations, ordering/removal, validation, import/export, preview playback, responsive layout, and draft disposal.');
} finally {
  await browser?.close();
  await new Promise(resolve => server ? server.close(resolve) : resolve());
  await rm(temporary, { recursive: true, force: true });
}
